// AI report rendering after the DOMPurify upgrade. Run with `npm test`.
import { test } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { JSDOM } from 'jsdom'
import createDOMPurify from 'dompurify'
import { sanitizeReportHtml } from '../src/utils/sanitizeReportHtml.js'

const here = new URL('.', import.meta.url)
const { window } = new JSDOM('')
const purify = createDOMPurify(window)
const clean = (html) => sanitizeReportHtml(html, purify)
const parse = (html) => new JSDOM(`<body>${html}</body>`).window.document

// Checks the parsed DOM, not the string: escaped payloads are meant to stay
// visible as text, so a regex over the HTML would flag them.
function assertInert (doc) {
  assert.equal(doc.querySelectorAll('script, iframe, object, embed, form, input, base, meta, link').length, 0)
  for (const el of doc.querySelectorAll('*')) {
    for (const { name, value } of el.attributes) {
      assert.ok(!/^on/i.test(name), `${el.tagName} keeps handler ${name}`)
      // Inline style is kept (the renderer uses it); javascript: inside CSS url()
      // does not execute in current browsers, so style is not checked here.
      if (/^(href|src|xlink:href|action|formaction)$/i.test(name)) {
        assert.ok(!/javascript:/i.test(value), `${el.tagName} ${name}=${value}`)
      }
    }
  }
}

test('installed DOMPurify is a patched release (>= 3.4.17)', () => {
  const { version } = JSON.parse(readFileSync(new URL('../node_modules/dompurify/package.json', here)))
  const [maj, min, pat] = version.split('.').map(Number)
  assert.ok(maj > 3 || (maj === 3 && (min > 4 || (min === 4 && pat >= 17))), version)
})

test('renderer output keeps its structure and stays inert', () => {
  // Generated by tests/fixtures/make_ai_report_fixture.py from the backend renderer,
  // with markup an LLM might emit in every free-text field.
  const raw = readFileSync(new URL('fixtures/ai-report.html', here), 'utf8')
  const doc = parse(clean(raw))
  assertInert(doc)
  assert.ok(doc.querySelector('h1')?.textContent.startsWith('Cluster health'))
  assert.ok(doc.querySelectorAll('h2').length >= 4)
  assert.ok(doc.querySelector('table th'), 'tables survive')
  // The escaped payload is shown to the reader as text, not executed.
  assert.match(doc.body.textContent, /<script>alert\(2\)<\/script>/)
  assert.equal(doc.querySelectorAll('script, img[onerror], a[href^="javascript"]').length, 0)
})

test('raw hostile markup is stripped, ordinary markup kept', () => {
  const raw = [
    '<h2>Findings</h2><ul><li><strong>pve3</strong> <code>92%</code></li></ul>',
    '<table><tr><th>Node</th><td>pve3</td></tr></table>',
    '<script>alert(1)</script>',
    '<img src="x" onerror="alert(2)">',
    '<a href="javascript:alert(3)">click</a>',
    '<svg><a xlink:href="javascript:alert(4)"><text>x</text></a></svg>',
    '<svg onload="alert(5)"></svg>',
    '<iframe src="https://evil.example"></iframe>',
    '<form action="https://evil.example"><input name="password"></form>',
    '<div style="background:url(javascript:alert(6))">styled</div>',
    '<math><mtext><table><mglyph><style><img src=x onerror=alert(7)></style></mglyph></table></mtext></math>',
  ].join('')
  const doc = parse(clean(raw))
  assertInert(doc)
  assert.equal(doc.querySelector('h2')?.textContent, 'Findings')
  assert.equal(doc.querySelector('li strong')?.textContent, 'pve3')
  assert.equal(doc.querySelector('th')?.textContent, 'Node')
  assert.equal(doc.querySelectorAll('iframe, script, form, input').length, 0)
  assert.equal(doc.querySelector('a')?.getAttribute('href'), null, 'javascript: href removed')
})

test('template-looking text stays plain text', () => {
  // v-html output is not compiled by Vue, so {{ }} is only text; DOMPurify must not
  // turn it into anything else either.
  const doc = parse(clean('<p>{{ constructor.constructor("alert(1)")() }}</p>'))
  assert.equal(doc.querySelector('p').textContent, '{{ constructor.constructor("alert(1)")() }}')
})

test('empty input renders nothing', () => {
  assert.equal(clean(''), '')
  assert.equal(clean(null), '')
  assert.equal(clean(undefined), '')
})

test('AIReportDetail renders report HTML only through the sanitizer', () => {
  const src = readFileSync(new URL('../src/views/AIReportDetail.vue', here), 'utf8')
  assert.match(src, /sanitizeReportHtml\(report\.value\?\.rendered_html\)/)
  assert.doesNotMatch(src, /DOMPurify\.sanitize/)
  // Every v-html binding in the view uses the sanitized value.
  const bindings = [...src.matchAll(/v-html="([^"]+)"/g)].map(m => m[1])
  assert.ok(bindings.length > 0)
  assert.deepEqual([...new Set(bindings)], ['safeRenderedHtml'])
})
